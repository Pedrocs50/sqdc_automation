WITH DADOS AS (
    SELECT dhos.*
    FROM DCM.DCM_HIST_OVERVIEW_STATION dhos
    WHERE dhos.DAT_ATLZ >= TO_DATE('15/06/2026', 'DD/MM/YYYY')
      AND dhos.DAT_ATLZ <  TO_DATE('23/06/2026', 'DD/MM/YYYY')
      AND dhos.NUM_IND_STATUS_NODE_REAL = 'PASSIVO'
      AND dhos.STR_POS_KEY = 'EJET'
      AND dhos.NUM_LV = 1
      AND dhos.NUM_ORIGINALID IN (
          14139, 14190, 15363, 14215,
          14162, 14234, 14259, 14281
      )
),
ULTIMA_ATUALIZACAO_DIA AS (
    SELECT
        TRUNC(DAT_ATLZ) AS DIA,
        MAX(DAT_ATLZ) AS ULTIMA_ATUALIZACAO
    FROM DADOS
    GROUP BY TRUNC(DAT_ATLZ)
)
SELECT
    ROUND(SUM(NVL(d.NUM_HH_SEM_ENTR, 0)), 3) AS TOTAL_HH,
    ROUND(SUM(NVL(d.NUM_FALTA, 0)), 3) AS TOTAL_FALTA,
    ROUND(SUM(NVL(d.NUM_TECNICO, 0)), 3) AS TOTAL_TECNICO
FROM DADOS d
INNER JOIN ULTIMA_ATUALIZACAO_DIA u
    ON d.DAT_ATLZ = u.ULTIMA_ATUALIZACAO;
