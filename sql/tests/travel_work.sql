SELECT
    h.STR_POS_DESCR,
    h.STR_POS_KEY,
    h.STR_FK_ID,
    h.NUM_ORIGINALID,
    h.STR_NODE_DESCR,
    h.NUM_LV,
    h.NUM_IND_ISLEAF,
    h.NUM_IND_STATUS_NODE_REAL,

    COUNT(*) AS qtd_linhas,
    COUNT(DISTINCT h.STR_PROJETO) AS qtd_avioes,

    ROUND(SUM(NVL(h.NUM_HH, 0)), 3) AS soma_hh_padrao,
    ROUND(AVG(NVL(h.NUM_HH, 0)), 3) AS media_hh_padrao,

    ROUND(SUM(NVL(h.NUM_HH_SEM_ENTR, 0)), 3) AS soma_hh_sem_entrave,
    ROUND(AVG(NVL(h.NUM_HH_SEM_ENTR, 0)), 3) AS media_hh_sem_entrave,

    MIN(h.DAT_ATLZ) AS primeira_atualizacao,
    MAX(h.DAT_ATLZ) AS ultima_atualizacao

FROM DCM.DCM_HIST_OVERVIEW_STATION h

WHERE h.DAT_ATLZ >= TO_DATE('15/06/2026', 'DD/MM/YYYY')
  AND h.DAT_ATLZ <  TO_DATE('22/06/2026', 'DD/MM/YYYY')
  AND h.STR_POS_DESCR = 'Travel Work MTO'
  AND h.NUM_IND_STATUS_NODE_REAL = 'PASSIVO'
  AND h.NUM_HH IS NOT NULL

GROUP BY
    h.STR_POS_DESCR,
    h.STR_POS_KEY,
    h.STR_FK_ID,
    h.NUM_ORIGINALID,
    h.STR_NODE_DESCR,
    h.NUM_LV,
    h.NUM_IND_ISLEAF,
    h.NUM_IND_STATUS_NODE_REAL

ORDER BY
    h.NUM_LV,
    h.STR_FK_ID,
    h.NUM_ORIGINALID,
    h.STR_NODE_DESCR;


