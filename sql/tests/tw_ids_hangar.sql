-- DESCOBRIR NODE DESCRIPTION
SELECT DISTINCT
    dhos.NUM_ORIGINALID,
    dhos.STR_POS_KEY,
    dhos.STR_POS_DESCR,
    dhos.STR_NODE_DESCR
FROM DCM.DCM_HIST_OVERVIEW_STATION dhos
WHERE dhos.NUM_LV = 1
  AND dhos.NUM_ORIGINALID IN (
      14139,
      14190,
      15363,
      14215,
      14162,
      14234,
      14259,
      14281
  )
ORDER BY
    dhos.NUM_ORIGINALID,
    dhos.STR_POS_KEY;

-- DESCOBRIR OS IDS
SELECT DISTINCT
    dhos.NUM_ORIGINALID,
    dhos.STR_NODE_DESCR,
    dhos.STR_POS_KEY,
    dhos.STR_POS_DESCR
FROM DCM.DCM_HIST_OVERVIEW_STATION dhos
WHERE dhos.STR_NODE_DESCR = 'Junção Fus./Pintura (GFW)'
  AND dhos.NUM_LV = 0
ORDER BY
    dhos.NUM_ORIGINALID;


-- TODOS IDS QUE TIVER JUNÇÃO OU PINTURA 
SELECT DISTINCT
    dhos.NUM_ORIGINALID,
    dhos.STR_NODE_DESCR
FROM DCM.DCM_HIST_OVERVIEW_STATION dhos
WHERE dhos.STR_POS_DESCR = 'Travel Work MTO'
  AND dhos.NUM_LV = 1
  AND dhos.STR_NODE_DESCR IS NOT NULL
  AND (
      UPPER(dhos.STR_NODE_DESCR) LIKE '%JUNÇÃO%'
      OR UPPER(dhos.STR_NODE_DESCR) LIKE '%PINTURA%'
  )
ORDER BY
    dhos.STR_NODE_DESCR,
    dhos.NUM_ORIGINALID;